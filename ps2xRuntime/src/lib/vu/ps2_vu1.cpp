// construction, execute/resume and XGKICK/PATH1. The shared engine is VuCore
// (ps2_vu_core.cpp, ps2_vu_recomp.cpp, ps2_vu_{upper,lower}.cpp). VX2: the
// generated-image, block, flag-elision and E36/E37/VRB1 trace code is gone.

